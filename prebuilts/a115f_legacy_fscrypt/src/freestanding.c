/*
 * Minimal freestanding memory helpers.
 *
 * The /init wrapper is linked without libc, and the vold shim must not
 * export interposing memcpy/memset symbols into vold's global namespace.
 * Marking these hidden keeps them private to each module while still
 * satisfying any compiler-emitted memory intrinsic calls.
 */

#include <stddef.h>

__attribute__((visibility("hidden"))) void *memcpy(void *dst, const void *src, size_t n) {
    unsigned char *d = (unsigned char *)dst;
    const unsigned char *s = (const unsigned char *)src;
    for (size_t i = 0; i < n; i++) {
        d[i] = s[i];
    }
    return dst;
}

__attribute__((visibility("hidden"))) void *memmove(void *dst, const void *src, size_t n) {
    unsigned char *d = (unsigned char *)dst;
    const unsigned char *s = (const unsigned char *)src;
    if (d < s) {
        for (size_t i = 0; i < n; i++) {
            d[i] = s[i];
        }
    } else if (d > s) {
        for (size_t i = n; i > 0; i--) {
            d[i - 1] = s[i - 1];
        }
    }
    return dst;
}

__attribute__((visibility("hidden"))) void *memset(void *dst, int c, size_t n) {
    unsigned char *d = (unsigned char *)dst;
    for (size_t i = 0; i < n; i++) {
        d[i] = (unsigned char)c;
    }
    return dst;
}
